-- ============================================================================
-- GRANTS MANAGEMENT SYSTEM (Government & Public Sector)
-- Relational Schema DDL for Oracle Database 21c XE (Normalized to 3NF)
-- Compatible with Oracle 19c/21c/23c and Oracle XE
-- ============================================================================

-- Drop tables in reverse dependency order if recreating
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'AUDIT_LOGS', 'PROGRESS_REPORTS', 'DISBURSEMENTS', 'REVIEW_SCORES', 
        'REVIEWS', 'APPLICATION_DOCUMENTS', 'APPLICATIONS', 
        'PROGRAM_ELIGIBILITY_CRITERIA', 'GRANT_PROGRAMS', 'USER_ROLES', 
        'USERS', 'ORGANIZATIONS', 'ROLES'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 1. ROLES (Master Table)
-- ----------------------------------------------------------------------------
CREATE TABLE ROLES (
    role_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code      VARCHAR2(30) NOT NULL UNIQUE,
    role_name      VARCHAR2(100) NOT NULL,
    description    VARCHAR2(255)
);

-- ----------------------------------------------------------------------------
-- 2. ORGANIZATIONS (Master / Entity Table: NGOs, Startups, Universities)
-- ----------------------------------------------------------------------------
CREATE TABLE ORGANIZATIONS (
    org_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_name             VARCHAR2(200) NOT NULL,
    org_type             VARCHAR2(50) NOT NULL 
                         CONSTRAINT chk_org_type CHECK (org_type IN (
                             'NGO', 'ACADEMIC_INSTITUTION', 'STARTUP', 
                             'RESEARCH_LAB', 'GOVERNMENT_BODY', 'PRIVATE_ENTERPRISE'
                         )),
    registration_number  VARCHAR2(50) NOT NULL UNIQUE,
    pan_number           VARCHAR2(10) NOT NULL UNIQUE,
    gstin                VARCHAR2(15),
    darpan_id            VARCHAR2(50),
    address_line1        VARCHAR2(255) NOT NULL,
    address_line2        VARCHAR2(255),
    city                 VARCHAR2(100) NOT NULL,
    state                VARCHAR2(100) NOT NULL,
    pincode              VARCHAR2(10) NOT NULL,
    bank_name            VARCHAR2(100) NOT NULL,
    bank_account_number  VARCHAR2(30) NOT NULL,
    ifsc_code            VARCHAR2(15) NOT NULL,
    annual_turnover_inr  NUMBER(15,2) DEFAULT 0 NOT NULL,
    established_year     NUMBER(4) NOT NULL,
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 3. USERS (Master Table: Administrators, Managers, Reviewers, Applicants)
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    user_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR2(60) NOT NULL UNIQUE,
    email            VARCHAR2(120) NOT NULL UNIQUE,
    password_hash    VARCHAR2(255) NOT NULL,
    full_name        VARCHAR2(120) NOT NULL,
    phone            VARCHAR2(20),
    designation      VARCHAR2(100),
    organization_id  NUMBER,
    status           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL 
                     CONSTRAINT chk_user_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED')),
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_users_org FOREIGN KEY (organization_id) REFERENCES ORGANIZATIONS(org_id) ON DELETE SET NULL
);

-- ----------------------------------------------------------------------------
-- 4. USER_ROLES (Junction Table: Many-to-Many Users and Roles)
-- ----------------------------------------------------------------------------
CREATE TABLE USER_ROLES (
    user_id NUMBER NOT NULL,
    role_id NUMBER NOT NULL,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_ur_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_ur_role FOREIGN KEY (role_id) REFERENCES ROLES(role_id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 5. GRANT_PROGRAMS (Master / Configuration Table: Grant Schemes)
-- ----------------------------------------------------------------------------
CREATE TABLE GRANT_PROGRAMS (
    program_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_code          VARCHAR2(50) NOT NULL UNIQUE,
    program_name          VARCHAR2(200) NOT NULL,
    category              VARCHAR2(100) NOT NULL,
    description           VARCHAR2(2000) NOT NULL,
    total_budget_inr      NUMBER(15,2) NOT NULL CONSTRAINT chk_tot_budget CHECK (total_budget_inr > 0),
    allocated_budget_inr  NUMBER(15,2) DEFAULT 0 NOT NULL CONSTRAINT chk_alloc_budget CHECK (allocated_budget_inr >= 0),
    disbursed_budget_inr  NUMBER(15,2) DEFAULT 0 NOT NULL CONSTRAINT chk_disb_budget CHECK (disbursed_budget_inr >= 0),
    min_award_inr         NUMBER(15,2) NOT NULL CONSTRAINT chk_min_award CHECK (min_award_inr > 0),
    max_award_inr         NUMBER(15,2) NOT NULL,
    opens_at              DATE NOT NULL,
    closes_at             DATE NOT NULL,
    status                VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL 
                          CONSTRAINT chk_program_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED', 'ARCHIVED')),
    created_by_user_id    NUMBER NOT NULL,
    created_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_award_range CHECK (max_award_inr >= min_award_inr),
    CONSTRAINT chk_dates CHECK (closes_at >= opens_at),
    CONSTRAINT fk_gp_created_by FOREIGN KEY (created_by_user_id) REFERENCES USERS(user_id)
);

-- ----------------------------------------------------------------------------
-- 6. PROGRAM_ELIGIBILITY_CRITERIA (Configuration child table)
-- ----------------------------------------------------------------------------
CREATE TABLE PROGRAM_ELIGIBILITY_CRITERIA (
    criteria_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id        NUMBER NOT NULL,
    criterion_type    VARCHAR2(50) NOT NULL,
    criterion_name    VARCHAR2(200) NOT NULL,
    criterion_value   VARCHAR2(255) NOT NULL,
    is_mandatory      NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT chk_is_mandatory CHECK (is_mandatory IN (0, 1)),
    CONSTRAINT fk_pec_program FOREIGN KEY (program_id) REFERENCES GRANT_PROGRAMS(program_id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 7. APPLICATIONS (Core Transaction Table: Grant Proposals)
-- ----------------------------------------------------------------------------
CREATE TABLE APPLICATIONS (
    application_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_number       VARCHAR2(50) NOT NULL UNIQUE,
    program_id               NUMBER NOT NULL,
    applicant_user_id        NUMBER NOT NULL,
    org_id                   NUMBER NOT NULL,
    project_title            VARCHAR2(255) NOT NULL,
    executive_summary        VARCHAR2(2000) NOT NULL,
    requested_amount_inr     NUMBER(15,2) NOT NULL CONSTRAINT chk_req_amt CHECK (requested_amount_inr > 0),
    approved_amount_inr      NUMBER(15,2),
    project_duration_months  NUMBER(3) NOT NULL CONSTRAINT chk_dur CHECK (project_duration_months > 0),
    eligibility_status       VARCHAR2(30) DEFAULT 'PENDING' NOT NULL 
                             CONSTRAINT chk_elig_status CHECK (eligibility_status IN ('PENDING', 'ELIGIBLE', 'INELIGIBLE')),
    eligibility_remarks      VARCHAR2(500),
    application_status       VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL 
                             CONSTRAINT chk_app_status CHECK (application_status IN (
                                 'DRAFT', 'SUBMITTED', 'UNDER_REVIEW', 'APPROVED', 
                                 'REJECTED', 'DISBURSED', 'CLOSED'
                             )),
    submission_date          TIMESTAMP,
    approval_date            TIMESTAMP,
    created_at               TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at               TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_app_program FOREIGN KEY (program_id) REFERENCES GRANT_PROGRAMS(program_id),
    CONSTRAINT fk_app_user FOREIGN KEY (applicant_user_id) REFERENCES USERS(user_id),
    CONSTRAINT fk_app_org FOREIGN KEY (org_id) REFERENCES ORGANIZATIONS(org_id)
);

-- ----------------------------------------------------------------------------
-- 8. APPLICATION_DOCUMENTS (Child Transaction Table: Supporting Attachments)
-- ----------------------------------------------------------------------------
CREATE TABLE APPLICATION_DOCUMENTS (
    doc_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id       NUMBER NOT NULL,
    document_type        VARCHAR2(60) NOT NULL,
    file_name            VARCHAR2(255) NOT NULL,
    file_size_bytes      NUMBER(12) NOT NULL,
    verification_status  VARCHAR2(30) DEFAULT 'VERIFIED' NOT NULL 
                         CONSTRAINT chk_doc_status CHECK (verification_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    uploaded_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_doc_app FOREIGN KEY (application_id) REFERENCES APPLICATIONS(application_id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 9. REVIEWS (Transaction Table: Reviewer Assignments and Evaluations)
-- ----------------------------------------------------------------------------
CREATE TABLE REVIEWS (
    review_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id    NUMBER NOT NULL,
    reviewer_user_id  NUMBER NOT NULL,
    assigned_date     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    completed_date    TIMESTAMP,
    total_score       NUMBER(5,2) CONSTRAINT chk_score_range CHECK (total_score BETWEEN 0 AND 100),
    recommendation    VARCHAR2(30) 
                      CONSTRAINT chk_rec CHECK (recommendation IN (
                          'RECOMMENDED', 'NOT_RECOMMENDED', 'RECOMMENDED_WITH_REVISIONS', 'PENDING'
                      )),
    comments          VARCHAR2(2000),
    review_status     VARCHAR2(30) DEFAULT 'ASSIGNED' NOT NULL 
                      CONSTRAINT chk_rev_status CHECK (review_status IN ('ASSIGNED', 'IN_PROGRESS', 'COMPLETED')),
    CONSTRAINT uq_app_reviewer UNIQUE (application_id, reviewer_user_id),
    CONSTRAINT fk_rev_app FOREIGN KEY (application_id) REFERENCES APPLICATIONS(application_id) ON DELETE CASCADE,
    CONSTRAINT fk_rev_reviewer FOREIGN KEY (reviewer_user_id) REFERENCES USERS(user_id)
);

-- ----------------------------------------------------------------------------
-- 10. REVIEW_SCORES (Detailed Criterion Scoring per Review)
-- ----------------------------------------------------------------------------
CREATE TABLE REVIEW_SCORES (
    score_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id       NUMBER NOT NULL,
    criterion_name  VARCHAR2(100) NOT NULL,
    max_score       NUMBER(3) NOT NULL,
    assigned_score  NUMBER(5,2) NOT NULL CONSTRAINT chk_item_score CHECK (assigned_score >= 0),
    remarks         VARCHAR2(500),
    CONSTRAINT fk_score_review FOREIGN KEY (review_id) REFERENCES REVIEWS(review_id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 11. DISBURSEMENTS (Transaction Table: Tranches & Financial Payments)
-- ----------------------------------------------------------------------------
CREATE TABLE DISBURSEMENTS (
    disbursement_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id        NUMBER NOT NULL,
    tranche_number        NUMBER(2) NOT NULL,
    amount_inr            NUMBER(15,2) NOT NULL CONSTRAINT chk_disb_amt CHECK (amount_inr > 0),
    milestone_description VARCHAR2(255) NOT NULL,
    scheduled_date        DATE NOT NULL,
    disbursed_date        DATE,
    payment_status        VARCHAR2(30) DEFAULT 'PENDING' NOT NULL 
                          CONSTRAINT chk_pay_status CHECK (payment_status IN ('PENDING', 'PROCESSING', 'DISBURSED', 'ON_HOLD', 'FAILED')),
    utr_number            VARCHAR2(50),
    disbursed_by_user_id  NUMBER,
    remarks               VARCHAR2(500),
    created_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_app_tranche UNIQUE (application_id, tranche_number),
    CONSTRAINT fk_disb_app FOREIGN KEY (application_id) REFERENCES APPLICATIONS(application_id) ON DELETE CASCADE,
    CONSTRAINT fk_disb_user FOREIGN KEY (disbursed_by_user_id) REFERENCES USERS(user_id)
);

-- ----------------------------------------------------------------------------
-- 12. PROGRESS_REPORTS (Transaction Table: Milestone & Fund Utilization)
-- ----------------------------------------------------------------------------
CREATE TABLE PROGRESS_REPORTS (
    report_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      NUMBER NOT NULL,
    report_title        VARCHAR2(200) NOT NULL,
    milestone_achieved  VARCHAR2(2000) NOT NULL,
    funds_utilized_inr  NUMBER(15,2) NOT NULL CONSTRAINT chk_fund_util CHECK (funds_utilized_inr >= 0),
    submission_date     DATE DEFAULT CURRENT_DATE NOT NULL,
    status              VARCHAR2(30) DEFAULT 'SUBMITTED' NOT NULL 
                        CONSTRAINT chk_rep_status CHECK (status IN ('SUBMITTED', 'VERIFIED', 'NEEDS_CLARIFICATION')),
    remarks             VARCHAR2(500),
    CONSTRAINT fk_rep_app FOREIGN KEY (application_id) REFERENCES APPLICATIONS(application_id) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 13. AUDIT_LOGS (System History & Governance Tracking)
-- ----------------------------------------------------------------------------
CREATE TABLE AUDIT_LOGS (
    log_id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name           VARCHAR2(50) NOT NULL,
    entity_id             NUMBER NOT NULL,
    action                VARCHAR2(50) NOT NULL,
    performed_by_user_id  NUMBER NOT NULL,
    old_state             VARCHAR2(255),
    new_state             VARCHAR2(255),
    details               VARCHAR2(1000),
    action_timestamp      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_audit_user FOREIGN KEY (performed_by_user_id) REFERENCES USERS(user_id)
);

-- ============================================================================
-- PERFORMANCE & FOREIGN KEY INDEXES
-- ============================================================================
CREATE INDEX idx_users_org_id ON USERS(organization_id);
CREATE INDEX idx_users_email ON USERS(email);

CREATE INDEX idx_gp_created_by ON GRANT_PROGRAMS(created_by_user_id);
CREATE INDEX idx_gp_status ON GRANT_PROGRAMS(status);
CREATE INDEX idx_gp_dates ON GRANT_PROGRAMS(opens_at, closes_at);

CREATE INDEX idx_pec_prog_id ON PROGRAM_ELIGIBILITY_CRITERIA(program_id);

CREATE INDEX idx_app_prog_id ON APPLICATIONS(program_id);
CREATE INDEX idx_app_user_id ON APPLICATIONS(applicant_user_id);
CREATE INDEX idx_app_org_id ON APPLICATIONS(org_id);
CREATE INDEX idx_app_status ON APPLICATIONS(application_status);
CREATE INDEX idx_app_elig ON APPLICATIONS(eligibility_status);

CREATE INDEX idx_app_doc_app_id ON APPLICATION_DOCUMENTS(application_id);

CREATE INDEX idx_rev_app_id ON REVIEWS(application_id);
CREATE INDEX idx_rev_reviewer ON REVIEWS(reviewer_user_id);
CREATE INDEX idx_rev_status ON REVIEWS(review_status);

CREATE INDEX idx_score_review ON REVIEW_SCORES(review_id);

CREATE INDEX idx_disb_app_id ON DISBURSEMENTS(application_id);
CREATE INDEX idx_disb_status ON DISBURSEMENTS(payment_status);

CREATE INDEX idx_rep_app_id ON PROGRESS_REPORTS(application_id);

CREATE INDEX idx_audit_entity ON AUDIT_LOGS(entity_name, entity_id);
CREATE INDEX idx_audit_user ON AUDIT_LOGS(performed_by_user_id);

COMMIT;
